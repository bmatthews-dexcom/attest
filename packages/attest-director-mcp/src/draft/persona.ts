/**
 * Persona generator — Phase 3 artifact.
 *
 * Produces `persona.md` matching the format of
 * `packages/attest-experts/agents/<id>/instructions.md`. The template bakes
 * in:
 *
 *   - Profile (name / mission / scope / don't-do list)
 *   - Responsibilities
 *   - 3-5 shot few-shot exemplars (built from the role brief's
 *     example_task + typical IO)
 *   - "What this role explicitly does NOT do" — the aiwolfdial-2024
 *     negatives technique
 *   - Self-check checklist (Inception Platform Prompt Guide shape)
 *
 * The real Director LLM-authors the persona using a research-grounded
 * drafting prompt; this file is the deterministic scaffold with slots.
 */
import type { RoleBrief } from "../schema/role-brief.js";
import type { Persona } from "../schema/draft.js";

export function generatePersona(brief: RoleBrief): Persona {
  const title = brief.title.trim();
  const typicalInputs = brief.typical_inputs
    .map((i) => `- \`${i.name}\` (\`${i.type}\`)${i.example ? ` — e.g. ${inline(i.example)}` : ""}`)
    .join("\n");
  const typicalOutputs = brief.typical_outputs
    .map((o) => `- \`${o.name}\` (\`${o.type}\`)${o.example ? ` — e.g. ${inline(o.example)}` : ""}`)
    .join("\n");
  const responsibilities = brief.responsibilities.map((r) => `- ${r}`).join("\n");

  const negatives = generateNegatives(brief);
  const negativesSection = negatives.map((n) => `- ${n}`).join("\n");

  const exemplars = generateFewShotExemplars(brief);
  const exemplarSection = exemplars
    .map(
      (ex, i) =>
        `### Exemplar ${i + 1}: ${ex.title}\n\n**Input:**\n\n\`\`\`\n${ex.input}\n\`\`\`\n\n**Response:**\n\n${ex.response}\n`,
    )
    .join("\n");

  const body = `# ${title}

<!--
Generated by attest-director — Phase 3 draft (${brief.id}).
Edit via refinement (/director refine ${brief.role}) — never in place.
-->

## Mission

${brief.mission.trim()}

## Scope

- **Domain:** ${brief.domain_context ?? "(context from role brief)"}
- **Form factor hint:** ${brief.form_factor_preference}
- **Called by:** chief dispatch via \`attest-mcp.invoke_expert\`.
- **Called with:** the attest expert input schema; see \`schema.json\`.

## Responsibilities

${responsibilities}

## Typical inputs

${typicalInputs}

## Typical outputs

${typicalOutputs}

## Few-shot exemplars

${exemplarSection}

## What this role explicitly does NOT do

${negativesSection}

## Self-check checklist (run before \`submit_report\`)

- [ ] Did I ground every finding on a specific file/line, URL, or quoted snippet?
- [ ] Does my output honor the typical_outputs schema in \`schema.json\`?
- [ ] Did I avoid any capability outside the capability map in \`capabilities.ts\`?
- [ ] Would a reviewer be able to reproduce my conclusion from the evidence I cited?
- [ ] Am I staying inside the responsibilities list above?

## Operating rules

- Call \`submit_report\` exactly once; no partial reports.
- Prefer bounded shell actions on the \`shell:safe\` allowlist.
- Never write to source outside the capability map's \`writes\` scope.
- When uncertain, surface a blocker and stop — don't guess.
`;

  return {
    markdown: body,
    lineCount: body.split("\n").length,
    negativesSection: negatives.join("; "),
  };
}

/**
 * Build the "would not say" negatives list — load-bearing per the
 * AiWolfDial-2024 persona-reproduction result.
 */
export function generateNegatives(brief: RoleBrief): string[] {
  const base = [
    `Do not write outside the capability map (writes: ${brief.requested_capabilities.writes.join(", ") || "none"}).`,
    "Do not call unapproved MCP tools or shell outside the `shell:safe` allowlist.",
    "Do not generate deliverables matching a different role brief — stay in the mission.",
    "Do not fabricate findings; every claim cites a file/line, URL, or quoted snippet.",
    "Do not escalate before you have genuinely tried the next bounded action.",
  ];
  // Domain hints: Jira-shaped briefs get a Jira-specific negative.
  if (/jira|atlassian|rovo/i.test(brief.mission + brief.title)) {
    base.push("Do not write to Jira (comment, transition, assignee) without an explicit `write:jira` approval.");
  }
  if (/healthcare|patient|phi|pii/i.test(brief.mission + (brief.domain_context ?? ""))) {
    base.push("Do not include unredacted PHI/PII in reports — redact before writing.");
  }
  return base;
}

/**
 * Build 3 few-shot exemplars from the brief's example_task + typical IO.
 * The real Director produces these grounded in Phase 2 research probes;
 * this scaffold produces structural exemplars that pass eval harness
 * loaders without claiming to be the final content.
 */
export function generateFewShotExemplars(brief: RoleBrief): Array<{
  title: string;
  input: string;
  response: string;
}> {
  const exampleInput = brief.typical_inputs[0];
  const exampleOutput = brief.typical_outputs[0];
  const baseInput = exampleInput?.example ?? brief.example_task;
  const baseOutput = exampleOutput?.example ?? `# ${brief.title} — report\n\n(ground on the input above)`;

  return [
    {
      title: "Nominal path",
      input: baseInput,
      response: baseOutput,
    },
    {
      title: "Edge: input missing a required field",
      input: `${baseInput}\n\n(missing field "${exampleInput?.name ?? "primary-input"}")`,
      response: `Report blocker: input missing \`${exampleInput?.name ?? "primary-input"}\`; return empty findings and set \`done: false\` with an actionable blocker message.`,
    },
    {
      title: "Edge: no results match the scope",
      input: `${baseInput}\n\n(empty result set)`,
      response: `Report an empty finding set with \`done: true\` and \`summary\` explaining the empty-set outcome — do not fabricate findings.`,
    },
  ];
}

function inline(s: string): string {
  return s.replace(/\n/g, " ").slice(0, 160);
}
