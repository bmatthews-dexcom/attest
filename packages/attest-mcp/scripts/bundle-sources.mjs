#!/usr/bin/env node
/**
 * bundle-sources.mjs — copy the attest source material the MCP server
 * needs at runtime into packages/attest-mcp/bundled/ so a user who runs
 *   npx -y attest-mcp
 * gets a self-contained server (no attest checkout required).
 *
 * Precedence at runtime (see src/sources.ts):
 *   1. ATTEST_ROOT env var (points at a live attest checkout) — wins
 *   2. ./bundled/* inside the installed package (this script's output)
 *
 * What we bundle:
 *   scripts/validators/   — all validate-*.sh plus _lib.sh, _lib_sdlc_config.sh,
 *                           and the three orchestrators (phase-gate / coverage /
 *                           handoff). The validators source _lib.sh via a
 *                           relative path, so the whole directory must ship.
 *   rules/*.md            — the glob-scoped rules (fed to the catalog)
 *   agents/shared/*.md    — the shared protocols exposed via
 *                           attest://protocols/<name>
 *   agents/*.md           — primary + cluster expert agents (prompts)
 *   commands/*.md         — sdlc-* command bodies (optional reference)
 *
 * No transforms (unlike build-target-claude.mjs) — the shell scripts and
 * protocol markdown ship verbatim; translation/compat lives in the MCP
 * tool layer, not in the sources.
 */

import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(SCRIPT_DIR, "..");
const REPO_ROOT = resolve(PKG_ROOT, "..", "..");
const OUT_DIR = join(PKG_ROOT, "bundled");

const COPY_TREES = [
  "scripts/validators",
  "rules",
  "agents/shared",
  "agents",
  "commands",
];

function copyTree(rel) {
  const src = join(REPO_ROOT, rel);
  if (!existsSync(src)) {
    console.warn(`[bundle-sources] WARNING: source missing: ${rel}`);
    return 0;
  }
  const dest = join(OUT_DIR, rel);
  mkdirSync(dirname(dest), { recursive: true });
  cpSync(src, dest, {
    recursive: true,
    filter: (s) => {
      // skip anything inside agents/ that's not .md (templates/, schemas/)
      // but keep agents/shared/blocks/ and agents/shared/includes/ markdown.
      const st = statSync(s);
      if (st.isDirectory()) return true;
      if (rel === "agents" && !s.endsWith(".md")) return false;
      if (rel === "commands" && !s.endsWith(".md")) return false;
      if (rel === "rules" && !s.endsWith(".md")) return false;
      if (rel === "agents/shared" && !s.endsWith(".md")) return false;
      return true;
    },
  });
  let count = 0;
  const walk = (d) => {
    for (const e of readdirSync(d)) {
      const p = join(d, e);
      if (statSync(p).isDirectory()) walk(p);
      else count++;
    }
  };
  walk(dest);
  return count;
}

function main() {
  if (existsSync(OUT_DIR)) rmSync(OUT_DIR, { recursive: true, force: true });
  mkdirSync(OUT_DIR, { recursive: true });

  const counts = {};
  for (const t of COPY_TREES) counts[t] = copyTree(t);

  const manifest = {
    bundledAt: new Date().toISOString(),
    attestRoot: REPO_ROOT,
    trees: counts,
    note:
      "Generated by scripts/bundle-sources.mjs. Overridden at runtime by " +
      "ATTEST_ROOT env var when set.",
  };
  writeFileSync(
    join(OUT_DIR, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n",
  );

  const total = Object.values(counts).reduce((a, b) => a + b, 0);
  console.log(`[bundle-sources] wrote ${total} files to ${OUT_DIR}`);
  for (const [t, c] of Object.entries(counts)) {
    console.log(`  ${c.toString().padStart(5)}  ${t}`);
  }
}

main();
